#include "twine.h"



/*
 TWINE S-box
*/


static const uint8_t SBOX[16]=
{

0xc,0x0,0xf,0xa,
0x2,0xb,0x9,0x5,
0x8,0x3,0xd,0x7,
0x1,0xe,0x6,0x4

};



static const uint8_t INV_SBOX[16]=
{

0x1,0xc,0x4,0xb,
0xf,0x7,0xe,0x8,
0x3,0x6,0x9,0x2,
0xa,0xd,0x0,0x5

};



uint8_t twine_sbox(uint8_t x)
{
    return SBOX[x&0xf];
}



uint8_t twine_inv_sbox(uint8_t x)
{
    return INV_SBOX[x&0xf];
}
