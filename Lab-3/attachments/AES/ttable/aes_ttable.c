void AES_TTable_KeyExpansion(
uint8_t *rk,
const uint8_t *key)
{

for(int i=0;i<16;i++)
rk[i]=key[i];


int bytes=16;
int r=0;


uint8_t temp[4];


while(bytes<176)
{

for(int i=0;i<4;i++)
temp[i]=rk[bytes-4+i];


if(bytes%16==0)
{

uint8_t t=temp[0];


temp[0]=sbox[temp[1]];
temp[1]=sbox[temp[2]];
temp[2]=sbox[temp[3]];
temp[3]=sbox[t];


temp[0]^=Rcon[r++];

}



for(int i=0;i<4;i++)
{

rk[bytes]=rk[bytes-16]^temp[i];

bytes++;

}


}


}


void AddRoundKey(
uint32_t state[4],
uint8_t *rk)
{

for(int i=0;i<4;i++)
{

state[i]^=
((uint32_t)rk[4*i]<<24)|
((uint32_t)rk[4*i+1]<<16)|
((uint32_t)rk[4*i+2]<<8)|
rk[4*i+3];

}

}


