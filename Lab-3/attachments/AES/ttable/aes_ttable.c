uint8_t xtime(uint8_t x)
{
    return 
    (x<<1)^((x&0x80)?0x1b:0);
}


uint8_t mul2(uint8_t x)
{
    return xtime(x);
}


uint8_t mul3(uint8_t x)
{
    return xtime(x)^x;
}

